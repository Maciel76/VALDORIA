function coast(poly,rng){
  const points=[];
  for(let i=0;i<poly.length;i++){
    const a=poly[i],b=poly[(i+1)%poly.length];
    points.push(a);
    for(const t of [.22,.44,.63,.84]){
      const wiggle=(rng()-.5)*.30;
      points.push([a[0]+(b[0]-a[0])*t+(b[1]-a[1])*wiggle,a[1]+(b[1]-a[1])*t-(b[0]-a[0])*wiggle]);
    }
  }
  return points;
}
export const atlasPoints=islands.map((p,i)=>coast(p,random(97+i*241)));
export const inside=(x,y,poly)=>{
  let result=false;
  for(let i=0,j=poly.length-1;i<poly.length;j=i++){
    const [xi,yi]=poly[i], [xj,yj]=poly[j];
    if((yi>y)!==(yj>y)&&x<(xj-xi)*(y-yi)/(yj-yi)+xi)result=!result;
  }
  return result;
};

export const onAtlasLand = (x,y) => atlasPoints.some(poly=>inside(x,y,poly));
